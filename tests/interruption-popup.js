const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../assets/interruption-popup.js'), 'utf8'), context);
const render = context.window.geonetInterruptionPopup;
const subscriber = { name: '<img src=x onerror=alert(1)>', id: 'SUB-1008', status: 'offline', address: 'Test', barangay: 'Test' };
const report = { id: 12, status: 'reported', reported_at: '2026-11-13 10:00:00' };
const techs = [{ id: 1, full_name: 'Tech one', availability: 'on_duty' }];
const html = render(subscriber, report, techs);
assert(!html.includes('<img'), 'subscriber names must not inject HTML into Leaflet popups');
assert(html.includes('data-map-assign-interruption="12"') && html.includes('Tech one'), 'unassigned report should offer technician assignment');
const assigned = render(subscriber, { ...report, status: 'accepted', assigned_technician_id: 1, technician_name: 'Tech one' }, techs);
assert(assigned.includes('Reassign technician') && assigned.includes('Technician accepted'), 'accepted repair supports reassignment and displays progress');
const waiting = render(subscriber, { ...report, status: 'awaiting_confirmation', confirmation_due_at: '2026-11-13 15:00:00' }, techs);
assert(!waiting.includes('data-map-assign-interruption'), 'waiting for subscriber confirmation must not allow reassignment');
assert(waiting.includes('Only the subscriber') && waiting.includes('2026-11-13 15:00:00'), 'popup explains subscriber-only confirmation and deadline');
assert(!html.includes('data-map-approve'), 'map popup must not offer administrator restoration approval');
const resolved = render(subscriber, { ...report, status: 'resolved', resolution_method: 'automatic' }, techs);
assert(!resolved.includes('data-map-assign-interruption') && resolved.includes('Automatically confirmed'), 'closed repair displays automatic confirmation without assignment controls');
const missing = render(subscriber, null, techs);
assert(missing.includes('No active SMS interruption report') && !missing.includes('data-map-assign-interruption'), 'offline subscriber without report must not fabricate one');
assert(render(subscriber, report, []).includes('disabled'), 'assignment is disabled without active technician accounts');
console.log('PASS: interruption popup controls, confirmation rules, empty states, and HTML escaping');
